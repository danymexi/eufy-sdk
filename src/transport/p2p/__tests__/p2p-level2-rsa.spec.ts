import { constants, createCipheriv, generateKeyPairSync, publicEncrypt } from "node:crypto";
import { P2PSession, type P2PFrame } from "../p2p-session.js";
import {
  decryptP2PData,
  deriveLevel2KeyFromRsaGatewayInfo,
  p2pCommandEncryptionKey,
  parseDataFrameHeader,
} from "../codec.js";
import {
  DEVICE_SN,
  STATION_SN as ROUTER_STATION_SN,
  routerWithSession,
  type FakeP2PSession,
} from "./session-fixtures.js";

/**
 * Level-2 negotiation over an RSA cipher: a `get_ciphers` answer with an empty `ecc_private_key` and an
 * RSA `private_key`, whose station sends the 16-byte level-2 key RSA-encrypted (PKCS#1 v1.5) in
 * `CMD_GATEWAYINFO` and takes level-2 frames as AES-128-ECB under that key at encryption type 2.
 *
 * Every key here is generated by the spec; the serial and DID are synthetic.
 */
const STATION_SN = "T8790P0000000001";
const P2P_DID = "XXXXXXX-000000-XXXXX";
const ACCOUNT_ID = "0".repeat(40);
const CIPHER_ID = 10;
const SESSION_KEY = Buffer.from("00112233445566778899aabbccddeeff", "hex");

const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 1024 });
const PKCS8_B64 = privateKey.export({ type: "pkcs8", format: "der" }).toString("base64");
const PKCS1_PEM = privateKey.export({ type: "pkcs1", format: "pem" }).toString();

/** `cipher_id(2 LE) ‖ 0000 ‖ ciphertext ‖ 00 ‖ trailing bytes`, the decrypted gateway-info layout. */
function gatewayInfo(ciphertext: Buffer, cipherId = CIPHER_ID): Buffer {
  const head = Buffer.alloc(4);
  head.writeUInt16LE(cipherId, 0);
  return Buffer.concat([head, ciphertext, Buffer.from([0x00]), Buffer.alloc(11, 0x5a)]);
}

/** The session key under PKCS#1 v1.5 encryption padding, as the station sends it. */
function wrapped(key: Buffer = SESSION_KEY): Buffer {
  return publicEncrypt({ key: publicKey, padding: constants.RSA_PKCS1_PADDING }, key);
}

/** A raw RSA block (no padding applied), for shaping a malformed padding. */
function rawBlock(block: Buffer): Buffer {
  return publicEncrypt({ key: publicKey, padding: constants.RSA_NO_PADDING }, block);
}

describe("deriveLevel2KeyFromRsaGatewayInfo", () => {
  test("recovers the 16-byte key with a base64 PKCS#8 DER private key", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()), PKCS8_B64)).toEqual(SESSION_KEY);
  });

  test("recovers it with a PEM-armoured PKCS#1 private key", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()), PKCS1_PEM)).toEqual(SESSION_KEY);
  });

  test("answers undefined for a payload shorter than the modulus", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()).subarray(0, 100), PKCS8_B64)).toBeUndefined();
  });

  test("answers undefined for key material that is not an RSA key", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()), "bm90IGEga2V5")).toBeUndefined();
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()), "")).toBeUndefined();
  });

  test("answers undefined under another RSA key", () => {
    const other = generateKeyPairSync("rsa", { modulusLength: 1024 }).privateKey;
    const otherB64 = other.export({ type: "pkcs8", format: "der" }).toString("base64");
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped()), otherB64)).toBeUndefined();
  });

  test("answers undefined for a block that is not PKCS#1 v1.5 encryption padding", () => {
    const signaturePadded = Buffer.concat([
      Buffer.from([0x00, 0x01]),
      Buffer.alloc(109, 0xff),
      Buffer.from([0x00]),
      SESSION_KEY,
    ]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(rawBlock(signaturePadded)), PKCS8_B64)).toBeUndefined();
    const shortPad = Buffer.concat([
      Buffer.from([0x00, 0x02]),
      Buffer.alloc(7, 0x11),
      Buffer.from([0x00]),
      Buffer.alloc(118, 0x22),
    ]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(rawBlock(shortPad)), PKCS8_B64)).toBeUndefined();
  });

  test("answers undefined when the wrapped key is not 16 bytes", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(gatewayInfo(wrapped(Buffer.alloc(32, 1))), PKCS8_B64)).toBeUndefined();
  });
});

type SessionInternals = {
  negotiateLevel2Key(payload: Buffer): void;
  handleFrame(header: ReturnType<typeof parseDataFrameHeader>, payload: Buffer, dataType: number): void;
  connectAddress: unknown;
  send: (addr: unknown, type: Buffer, payload: Buffer) => void;
};

/** A session whose cipher answers an empty ECC key and the spec's RSA key, negotiated from a gateway info. */
async function negotiatedSession(stationSn = STATION_SN): Promise<{ session: P2PSession; ready: unknown[] }> {
  const session = new P2PSession({
    stationSn,
    p2pDid: P2P_DID,
    resolveCipherKey: async () => "",
    resolveRsaCipherKey: async (cipherId) => (cipherId === CIPHER_ID ? PKCS8_B64 : undefined),
  });
  const ready: unknown[] = [];
  session.on("level2Ready", (e) => ready.push(e));
  (session as unknown as SessionInternals).negotiateLevel2Key(gatewayInfo(wrapped()));
  await session.awaitLevel2Key(1_000);
  return { session, ready };
}

describe("P2PSession level-2 over an RSA cipher", () => {
  test("a cipher with no ECC key and an RSA key makes level 2 ready", async () => {
    const { session, ready } = await negotiatedSession();
    expect(await session.awaitLevel2Key(0)).toBe(true);
    expect(session.hasLevel2Key).toBe(false);
    expect(ready).toEqual([{ cipherId: CIPHER_ID }]);
  });

  test("a level-2 set-payload goes out AES-128-ECB under the negotiated key at encryption type 2", async () => {
    const { session } = await negotiatedSession();
    const internals = session as unknown as SessionInternals;
    const sent: Buffer[] = [];
    internals.connectAddress = { host: "127.0.0.1", port: 32100 };
    internals.send = (_addr, _type, payload) => sent.push(payload);

    expect(session.sendControlLevel2(2100, 0, ACCOUNT_ID, { isOpen: 1, userIndex: 0 }, 0)).toBe(true);

    expect(sent).toHaveLength(1);
    const frame = sent[0].subarray(4);
    const header = parseDataFrameHeader(frame);
    expect(header.commandId).toBe(1350);
    expect(header.channel).toBe(0);
    expect(header.signCode).toBe(2);
    const body = frame.subarray(16);
    expect(body.length).toBe(header.bytesToRead & 0xffff);
    const plain = decryptP2PData(body, SESSION_KEY).toString("utf-8").replace(/\0+$/, "");
    expect(JSON.parse(plain)).toEqual({
      account_id: ACCOUNT_ID,
      cmd: 2100,
      mChannel: 0,
      mValue3: 0,
      payload: { isOpen: 1, userIndex: 0 },
    });
  });

  test("an inbound frame at encryption type 2 is read AES-128-ECB under the negotiated key", async () => {
    const { session } = await negotiatedSession();
    const json = JSON.stringify({ cmd: 2100, payload: { ret: 0 } });
    const plain = Buffer.alloc(Math.ceil((json.length + 1) / 16) * 16);
    plain.write(json);
    const c = createCipheriv("aes-128-ecb", SESSION_KEY, null);
    c.setAutoPadding(false);
    const sealed = Buffer.concat([c.update(plain), c.final()]);
    const frames: P2PFrame[] = [];
    session.on("data", (f: P2PFrame) => frames.push(f));

    (session as unknown as SessionInternals).handleFrame(
      { commandId: 1351, bytesToRead: sealed.length, channel: 0, signCode: 2, type: 1 },
      sealed,
      0,
    );

    expect(frames[0]?.json).toEqual({ cmd: 2100, payload: { ret: 0 } });
  });
});

/** Each payload a connected session sends, as the frame header and body that follow the 4-byte DATA prefix. */
function capture(session: P2PSession): Array<{ header: ReturnType<typeof parseDataFrameHeader>; body: Buffer }> {
  const internals = session as unknown as SessionInternals & { connected: boolean };
  const sent: Array<{ header: ReturnType<typeof parseDataFrameHeader>; body: Buffer }> = [];
  internals.connected = true;
  internals.connectAddress = { host: "127.0.0.1", port: 32100 };
  internals.send = (_addr, _type, payload) => {
    const frame = payload.subarray(4);
    sent.push({ header: parseDataFrameHeader(frame), body: frame.subarray(16) });
  };
  return sent;
}

/**
 * The level the router picks from {@link P2PSession.hasLevel2Key} does not move on an RSA session: only a
 * set-payload that is level-2 only takes the negotiated key.
 */
describe("routing set-payload on an RSA session", () => {
  const PAYLOAD = { isOpen: 1, userIndex: 0 };
  const plainJson = (body: Buffer, key: Buffer) =>
    JSON.parse(decryptP2PData(body, key).toString("utf-8").replace(/\0+$/, ""));

  it("sends an auto-sealed set-payload level-1, under the level-1 key at encryption type 1", async () => {
    const { session } = await negotiatedSession(ROUTER_STATION_SN);
    const sent = capture(session);
    const router = routerWithSession(session as unknown as FakeP2PSession);

    await router.dispatchCommand(DEVICE_SN, {
      kind: "set-payload",
      cmd: 2100,
      payload: PAYLOAD,
      channel: 0,
      mValue3: 0,
      form: "auto",
    });

    expect(sent.length).toBeGreaterThan(0);
    const level1Key = Buffer.from(p2pCommandEncryptionKey(ROUTER_STATION_SN, P2P_DID));
    for (const { header, body } of sent) {
      expect(header.commandId).toBe(1350);
      expect(header.signCode).toBe(1);
      expect(plainJson(body, level1Key)).toMatchObject({ cmd: 2100, payload: PAYLOAD });
    }
  });

  it("sends a level-2-only set-payload under the negotiated key at encryption type 2", async () => {
    const { session } = await negotiatedSession(ROUTER_STATION_SN);
    const sent = capture(session);
    const router = routerWithSession(session as unknown as FakeP2PSession);

    await router.dispatchCommand(DEVICE_SN, {
      kind: "set-payload",
      cmd: 2100,
      payload: PAYLOAD,
      channel: 0,
      mValue3: 0,
    });

    expect(sent.length).toBeGreaterThan(0);
    for (const { header, body } of sent) {
      expect(header.commandId).toBe(1350);
      expect(header.signCode).toBe(2);
      expect(plainJson(body, SESSION_KEY)).toEqual({
        account_id: ACCOUNT_ID,
        cmd: 2100,
        mChannel: 0,
        mValue3: 0,
        payload: PAYLOAD,
      });
    }
  });
});
